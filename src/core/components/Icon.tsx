/** Icons whose glyph implies a direction and so flip by default under RTL. */
const DEFAULT_MIRRORED = new Set<IconName>(['chevronForward', 'arrowBack', 'signOut', 'send']);

export type IconProps = {
  name: IconName;
  size?: number;
  color?: string;
  /** Overrides the default RTL-mirror behaviour for this instance. */
  mirrorInRtl?: boolean;
};

type SvgProps = ComponentProps<typeof Svg>;

/**
 * Icons are decorative — the wrapping control owns the accessibility label,
 * so this is always hidden from the accessibility tree.
 *
 * The glyphs are Figma's own vector paths rather than an icon font, so the
 * stroke scales with `size` exactly as the design intends. `Svg` has no
 * `importantForAccessibility`; `accessibilityElementsHidden` plus
 * `importantForAccessibility` on the wrapper covers both platforms.
 */
export function Icon({ name, size = CANVAS, color, mirrorInRtl }: IconProps) {
  const theme = useTheme();
  const direction = useDirection();

  const shouldMirror = mirrorInRtl ?? DEFAULT_MIRRORED.has(name);
  const mirrored = direction === 'rtl' && shouldMirror;
  const stroke = color ?? theme.colors.iconDefault;

  const svgProps: SvgProps = {
    width: size,
    height: size,
    viewBox: `0 0 ${CANVAS} ${CANVAS}`,
    fill: 'none',
    accessibilityElementsHidden: true,
    importantForAccessibility: 'no-hide-descendants',
    style: mirrored ? { transform: [{ scaleX: -1 }] } : undefined,
  };

  return (
    <Svg {...svgProps}>
      {GLYPHS[name].map((entry, index) => {
        const path = typeof entry === 'string' ? { d: entry } : entry;
        return (
          <Path
            key={index}
            d={path.d}
            stroke={stroke}
            strokeWidth={STROKE_WIDTH}
            strokeLinecap={path.cap ?? 'round'}
            strokeLinejoin={path.join ?? 'round'}
          />
        );
      })}
    </Svg>
  );
}
